export default defineNuxtPlugin((nuxtApp) => {
  // Прокручиваемый контейнер здесь не окно, а .main, поэтому штатный scrollBehavior
  // роутера не работает и позицию приходится сбрасывать руками.
  //
  // Важно: page:finish срабатывает не только на переходах, но и на первой
  // гидратации. SSR-разметка видна задолго до неё, пользователь успевает
  // прокрутить страницу — и в момент, когда гидратация заканчивается, его
  // выбрасывает наверх. Дальше он кликает туда, где секунду назад была карточка,
  // и попадает в пустоту. Поэтому сбрасываем прокрутку только на настоящих
  // переходах между страницами.
  let navigating = false;

  nuxtApp.hook('page:start', () => {
    navigating = true;
  });

  nuxtApp.hook('page:finish', () => {
    if (!navigating) return;
    navigating = false;
    document.querySelector('.main')?.scrollTo({ top: 0 });
  });
});
